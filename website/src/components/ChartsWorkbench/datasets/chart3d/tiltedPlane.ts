// Plane (`surface`) preset — a COMPUTED reference plane `z = a*x + b*y + c`
// over an even grid, never vendored data. The user's own request ("a
// plane?"): a clean, minimal 3D reference plot with no data-reading
// ambiguity — every cell lies exactly on one flat plane, so it is the
// simplest possible surface to check the axis triad/camera/shading against.
import type { GlyphChart3dSurfaceGridData } from "@glyphcss/charts/3d";
import type { Chart3dSurfaceDataset } from "./types";

const N = 16;
const EXTENT = 5;
const A = 0.35, B = 0.55, C = 1;

const x: number[] = Array.from({ length: N }, (_, i) => -EXTENT + (2 * EXTENT * i) / (N - 1));
const y: number[] = Array.from({ length: N }, (_, i) => -EXTENT + (2 * EXTENT * i) / (N - 1));
const z: number[][] = y.map((yv) => x.map((xv) => A * xv + B * yv + C));

const data: GlyphChart3dSurfaceGridData = { z };

export const tiltedPlaneDataset: Chart3dSurfaceDataset = {
  id: "tilted-plane",
  markType: "surface",
  title: "Plane (z = 0.35x + 0.55y + 1)",
  description: "A tilted reference plane over an even grid — a computed example, not vendored data, for a clean 3D surface with no ambiguity about what the shape means.",
  source: { name: "Computed example (glyphcss)", url: "", licence: "N/A — generated by this repository's own math, not sourced data" },
  data,
  channels: { x, y },
  options: {
    axes: {
      x: { title: "x" },
      y: { title: "y" },
      z: { title: "z" },
    },
  },
};
