import { chromium } from "playwright";
const label = process.argv[2] || "snap";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
await page.goto("http://localhost:4323/wordart", { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
const pre = await page.locator(".wa-stage pre").first();
const text = await pre.textContent();
const html = await pre.evaluate(el => el.innerHTML);
await page.screenshot({ path: `/tmp/wordart_${label}.png` });
console.log(`=== ${label} ===`);
console.log("text length:", text.length);
console.log("html length:", html.length);
import { writeFileSync } from "fs";
writeFileSync(`/tmp/wordart_${label}.txt`, text);
writeFileSync(`/tmp/wordart_${label}.html`, html);
await browser.close();
