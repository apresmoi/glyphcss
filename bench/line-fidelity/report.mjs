// RESULTS.md writer.
import fs from "node:fs";
import { TERMS, WEIGHTS } from "./rubric.mjs";
import { STRATEGIES } from "./strategies.mjs";
import { TABLE_ANGLE_BUCKETS, TABLE_OFFSET_BINS } from "./oracle.mjs";
import { VOCABS } from "./vocab.mjs";

const FAMILIES = ["line", "circle", "arc", "corner", "wiggle"];
const f3 = (x) => (x === undefined || Number.isNaN(x) ? "–" : x.toFixed(3));
const f2 = (x) => (x === undefined || Number.isNaN(x) ? "–" : x.toFixed(2));
const pct = (x) => (x === undefined || Number.isNaN(x) ? "–" : `${(x * 100).toFixed(0)}%`);
const mean = (a) => (a.length ? a.reduce((s, x) => s + x, 0) / a.length : NaN);
const median = (a) => { if (!a.length) return NaN; const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const q = (a, p) => { if (!a.length) return NaN; const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };

function gridText(rec, cells) {
  const g = Array.from({ length: rec.rows }, () => Array(rec.cols).fill(" "));
  for (const [c, r, ch] of cells) g[r][c] = ch;
  let lines = g.map((r) => r.join(""));
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines.at(-1).trim()) lines.pop();
  return lines;
}

function sideBySide(blocks) {
  // Trim common left margin and pad to equal width; every glyph here is one cell wide.
  const trimmed = blocks.map(({ title, lines }) => {
    const lead = Math.min(...lines.filter((l) => l.trim()).map((l) => l.length - l.trimStart().length));
    const ls = lines.map((l) => [...l.slice(lead)].join("").trimEnd());
    return { title, lines: ls, w: Math.max(title.length, ...ls.map((l) => [...l].length)) };
  });
  const h = Math.max(...trimmed.map((b) => b.lines.length));
  const out = [trimmed.map((b) => b.title.padEnd(b.w)).join("   ")];
  for (let i = 0; i < h; i++) out.push(trimmed.map((b) => { const l = b.lines[i] ?? ""; return l + " ".repeat(b.w - [...l].length); }).join("   ").trimEnd());
  return out.join("\n");
}

export function writeReport(meta, results, file) {
  const L = [];
  const p = (s = "") => L.push(s);
  const byId = {};
  for (const face of Object.keys(results.cases)) {
    byId[face] = new Map(results.cases[face].map((r) => [r.id, r]));
    for (const [v, t] of Object.entries(results.tables[face])) for (const e of t.evals) { const r = byId[face].get(e.id); if (r) (r.table ??= {})[v] = e; }
  }
  const val = (face, pick, filter = () => true) => results.cases[face].filter(filter).map(pick).filter((x) => x !== undefined);
  const stratVals = (face, name, fam, key = "total") => val(face, (r) => r.strategies[name]?.score?.[key], (r) => !fam || r.family === fam);
  const dpVals = (face, v, fam, key = "total") => val(face, (r) => r.dp[v]?.score?.[key], (r) => !fam || r.family === fam);
  const tabVals = (face, v, fam, key = "total") => val(face, (r) => r.table?.[v]?.score?.[key], (r) => !fam || r.family === fam);

  p("# Line fidelity — results");
  p();
  p(`Generated by \`node bench/line-fidelity/run.mjs${meta.quick ? " --quick" : ""}\` (${meta.runtimeSec.toFixed(0)} s, ${meta.workers} workers, DP pruning M = ${meta.M}). Scores: lower is better; terms and weights are defined in \`rubric.mjs\` and explained in README.md. Every number is the FULL rubric re-scored on the composited glyph image, including the DP oracle's.`);
  p();
  p("Weights: " + TERMS.map((k) => `${k} ${k === "angle" ? "1/45 per °" : WEIGHTS[k]}`).join(" · ") + ".");
  p();

  // ── Faces ──
  p("## Faces, cells and compositing validation");
  p();
  p("| face | used by | cell (device px @ DPR 4, 16 px font) | safe candidates | composite vs DOM screenshot (rel. L1 / max px) |");
  p("|---|---|---|---|---|");
  for (const [f, fmeta] of Object.entries(meta.faces)) {
    const gs = Object.values(fmeta.glyphs);
    const v = meta.validation[f];
    p(`| ${fmeta.label} | ${f === "atlas" ? "scenes, /maps (Chromium default)" : "/charts, /diagrams, every spans fallback"} | ${fmeta.cellW.toFixed(3)} × ${fmeta.cellH}, ${fmeta.phases} sub-px phases | ${gs.filter((g) => g.safe).length} / ${gs.length} | ${(v.relL1 * 100).toFixed(3)}% / ${v.maxPixelErr.toFixed(3)} |`);
  }
  p();
  for (const [f, fmeta] of Object.entries(meta.faces)) {
    const unsafe = Object.entries(fmeta.glyphs).filter(([, g]) => !g.safe);
    const groups = {};
    for (const [g, x] of unsafe) (groups[x.reason] ??= []).push(g);
    p(`- **${f}** unsafe: ` + (Object.entries(groups).map(([r, gs]) => `${r} (${gs.length}): \`${gs.join("")}\``).join("; ") || "none"));
  }
  p();

  // ── Glyph positions ──
  if (meta.glyphPositions) {
    p("## Where the oriented glyphs really sit (line-height 1)");
    p();
    p("`inkGlyphForTangent` picks a horizontal glyph by the stroke's sub-row (‾ < 1/6 ≤ ▔ < 1/3 ≤ - < 2/3 ≤ _) and a vertical one by sub-column (▏ < 1/3 ≤ | < 2/3 ≤ ▕), from a Menlo census. Measured ink centroid and extent (R ≥ 0.3) in each site face, as fractions of the cell (row 0 = cell top, 1 = cell bottom):");
    p();
    p("| glyph | " + Object.keys(meta.glyphPositions).map((f) => `${f} centroid row / col · ink rows`).join(" | ") + " |");
    p("|---|" + Object.keys(meta.glyphPositions).map(() => "---").join("|") + "|");
    for (const g of Object.keys(meta.glyphPositions.atlas ?? {})) {
      p(`| \`${g === "|" ? "\\|" : g}\` | ${Object.values(meta.glyphPositions).map((gp) => { const x = gp[g]; return x ? `${x.row.toFixed(2)} / ${x.col.toFixed(2)} · [${x.top.toFixed(2)}, ${x.bottom.toFixed(2)}]` : "–"; }).join(" | ")} |`);
    }
    p();
  }

  // ── Headline ──
  // best-known(own) = per case, the best of: every current strategy sharing the vocabulary on that face, its table, its DP.
  const ownOf = (st) => (st.vocab === "wire" ? "all" : st.vocab);
  const bestKnown = (face, r, v) => {
    const xs = [r.dp[v]?.score?.total, r.table?.[v]?.score?.total];
    for (const [n, st] of Object.entries(STRATEGIES)) if (st.face === face && (v === "all" || ownOf(st) === v)) xs.push(r.strategies[n]?.score?.total);
    if (v === "all") for (const k of Object.keys(VOCABS)) xs.push(r.dp[k]?.score?.total, r.table?.[k]?.score?.total);
    return Math.min(...xs.filter((x) => x !== undefined));
  };
  const famMean = (vals) => mean(FAMILIES.map((fam) => mean(vals(fam))).filter((x) => !Number.isNaN(x)));
  const bkVals = (face, v, fam) => val(face, (r) => bestKnown(face, r, v), (r) => !fam || r.family === fam);
  p("## Headline: current vs lookup table vs DP oracle");
  p();
  p("Family-balanced mean rubric total (the mean of the five family means, so the 720 straight lines do not drown the 29 curves), each strategy on the face the site draws it in. *own* = restricted to the strategy's own glyph family; *all* = every safe glyph of that face. *best known* = per case, the best of the DP, the table and every current strategy in that vocabulary (the DP is a heuristic optimum and does not always beat the incumbent — see the DP section). Headroom = 1 − best known / current.");
  p();
  p("| strategy | face | vocab | current | table (own) | DP (own) | best known (own) | DP (all) | best known (all) | headroom own | headroom all |");
  p("|---|---|---|---|---|---|---|---|---|---|---|");
  for (const [name, st] of Object.entries(STRATEGIES)) {
    const face = st.face, v = ownOf(st);
    const cur = famMean((fam) => stratVals(face, name, fam));
    const bo = famMean((fam) => bkVals(face, v, fam)), ba = famMean((fam) => bkVals(face, "all", fam));
    p(`| ${name} | ${face} | ${v} | ${f3(cur)} | ${f3(famMean((fam) => tabVals(face, v, fam)))} | ${f3(famMean((fam) => dpVals(face, v, fam)))} | ${f3(bo)} | ${f3(famMean((fam) => dpVals(face, "all", fam)))} | ${f3(ba)} | ${pct(1 - bo / cur)} | ${pct(1 - ba / cur)} |`);
  }
  p();
  p("Per family — current → best known (own) / best known (all):");
  p();
  p("| strategy | " + FAMILIES.join(" | ") + " |");
  p("|---|" + FAMILIES.map(() => "---").join("|") + "|");
  for (const [name, st] of Object.entries(STRATEGIES)) {
    const face = st.face, v = ownOf(st);
    p(`| ${name} | ${FAMILIES.map((fam) => `${f2(mean(stratVals(face, name, fam)))} → ${f2(mean(bkVals(face, v, fam)))} / ${f2(mean(bkVals(face, "all", fam)))}`).join(" | ")} |`);
  }
  p();

  // ── Terms ──
  p("## Rubric terms (mean over all cases)");
  p();
  p("| strategy | variant | " + TERMS.join(" | ") + " | total |");
  p("|---|---|" + TERMS.map(() => "---").join("|") + "|---|");
  for (const [name, st] of Object.entries(STRATEGIES)) {
    const face = st.face, v = st.vocab === "wire" ? "all" : st.vocab;
    const row = (label, get) => p(`| ${name} | ${label} | ${[...TERMS, "total"].map((k) => (k === "angle" ? f2(mean(get(k))) : f3(mean(get(k))))).join(" | ")} |`);
    row("current", (k) => stratVals(face, name, undefined, k));
    row(`table ${v}`, (k) => tabVals(face, v, undefined, k));
    row(`DP ${v}`, (k) => dpVals(face, v, undefined, k));
    if (v !== "all") row("DP all", (k) => dpVals(face, "all", undefined, k));
  }
  p();
  p("Units: chamfer, p95, maxGap in cell widths; gap and stray are fractions; angle in degrees; cv dimensionless.");
  p();

  // ── Vocab summary ──
  p("## What each glyph family can reach (both faces)");
  p();
  p("| face | vocab | K | table | DP | DP lines | DP circles+arcs | DP corners | DP wiggles |");
  p("|---|---|---|---|---|---|---|---|---|");
  for (const face of Object.keys(results.cases)) {
    for (const v of Object.keys(VOCABS)) {
      const K = results.cases[face][0]?.dp[v]?.K;
      p(`| ${face} | ${v} (${VOCABS[v].label}) | ${K} | ${f3(mean(tabVals(face, v)))} | ${f3(mean(dpVals(face, v)))} | ${f3(mean(dpVals(face, v, "line")))} | ${f3(mean([...dpVals(face, v, "circle"), ...dpVals(face, v, "arc")]))} | ${f3(mean(dpVals(face, v, "corner")))} | ${f3(mean(dpVals(face, v, "wiggle")))} |`);
    }
  }
  p();
  p("Straight-line means here are per case (720 of 749 cases are lines).");
  p();

  // ── Angle profile ──
  p("## Straight lines by angle (mean over 4 offsets × 2 lengths)");
  p();
  const lineRecs = (face) => results.cases[face].filter((r) => r.family === "line");
  const angles = [...new Set(lineRecs("atlas").map((r) => r.params.deg))].sort((a, b) => a - b);
  const angleMean = (face, deg, get) => mean(lineRecs(face).filter((r) => r.params.deg === deg).map(get).filter((x) => x !== undefined));
  const shown = ["maps-ink", "maps-box", "maps-braille", "scene-ink", "canvas-box", "canvas-braille"];
  p("| angle | " + shown.map((n) => `${n} (cur / DP own)`).join(" | ") + " | DP all (atlas) |");
  p("|---|" + shown.map(() => "---").join("|") + "|---|");
  for (const deg of angles.filter((d) => d % 10 === 0 || angles.length < 30)) {
    const cols = shown.map((n) => {
      const st = STRATEGIES[n];
      return `${f2(angleMean(st.face, deg, (r) => r.strategies[n]?.score?.total))} / ${f2(angleMean(st.face, deg, (r) => r.dp[st.vocab]?.score?.total))}`;
    });
    p(`| ${deg}° | ${cols.join(" | ")} | ${f2(angleMean("atlas", deg, (r) => r.dp.all?.score?.total))} |`);
  }
  p();
  p("### Worst angles of each current strategy");
  p();
  p("| strategy | 5 worst angles (current total → DP own) |");
  p("|---|---|");
  for (const [name, st] of Object.entries(STRATEGIES)) {
    const v = st.vocab === "wire" ? "all" : st.vocab;
    const per = angles.map((deg) => ({ deg, cur: angleMean(st.face, deg, (r) => r.strategies[name]?.score?.total), dp: angleMean(st.face, deg, (r) => r.dp[v]?.score?.total) })).filter((x) => !Number.isNaN(x.cur));
    per.sort((a, b) => b.cur - a.cur);
    p(`| ${name} | ${per.slice(0, 5).map((x) => `${x.deg}°: ${f2(x.cur)} → ${f2(x.dp)}`).join(", ")} |`);
  }
  p();

  // ── Renders ──
  p("## Renders, current vs oracle (verbatim cell text)");
  p();
  p("Atlas-face strategies print their source glyphs (the page draws them through the GlyphCssAtlas PUA code points). Totals in brackets.");
  p();
  const picks = [
    ["line L20 30° o0.25", ["maps-ink", "maps-box", "maps-braille"], ["ink", "box", "braille", "all"], "atlas"],
    ["line L20 60° o0.5", ["maps-ink", "scene-ink", "maps-box"], ["ink", "box", "all"], "atlas"],
    ["circle r6 o0", ["maps-ink", "maps-box", "maps-braille"], ["ink", "box", "all"], "atlas"],
    ["wiggle 0", ["maps-ink", "maps-braille"], ["ink", "all"], "atlas"],
    ["line L20 20° o0.25", ["canvas-box", "canvas-braille"], ["ink", "braille", "all"], "mono"],
  ];
  for (const [id, strats, vocabs, face] of picks) {
    const rec = byId[face]?.get(id);
    if (!rec) continue;
    const blocks = [];
    for (const n of strats) { const s = rec.strategies[n]; if (s?.cells) blocks.push({ title: `${n} [${f2(s.score.total)}]`, lines: gridText(rec, s.cells) }); }
    for (const v of vocabs) { const d = rec.dp[v]; if (d) blocks.push({ title: `DP ${v} [${f2(d.score.total)}]`, lines: gridText(rec, d.cells) }); }
    p(`**${id}** (${face})`);
    p();
    p("```text");
    p(sideBySide(blocks));
    p("```");
    p();
  }

  // ── Tables ──
  p("## The fitted lookup tables (atlas)");
  p();
  p(`Key = (tangent angle bucket of ${180 / TABLE_ANGLE_BUCKETS}° in visual space, band axis, offset of the cell centre from the line along the minor axis in ${TABLE_OFFSET_BINS} bins over [−1, 1) cells). One glyph per supercover cell, no DP. Fit by coordinate descent on the DP surrogate over a training subset (lines every 10° + every curve); evaluated on all cases. Rows: angle bucket centre; columns: offset bins (− = line above/left of the centre); \`·\`-free blanks shown as \`␣\`. Only keys that occur are shown.`);
  p();
  for (const v of ["ink", "all"]) {
    const t = results.tables.atlas?.[v];
    if (!t) continue;
    const map = new Map(t.table);
    p(`**${v}** (fit ${(t.fitMs / 1000).toFixed(0)} s on ${t.trainCases} cases)`);
    p();
    p("```text");
    p("angle  axis  " + Array.from({ length: TABLE_OFFSET_BINS }, (_, o) => String(o)).join(" "));
    for (let b = 0; b < TABLE_ANGLE_BUCKETS; b++) for (const ax of [0, 1]) {
      const row = Array.from({ length: TABLE_OFFSET_BINS }, (_, o) => { const g = map.get((b * 2 + ax) * TABLE_OFFSET_BINS + o); return g === undefined ? "." : g === " " ? "␣" : g; });
      if (row.every((x) => x === ".")) continue;
      p(`${String((b * 180) / TABLE_ANGLE_BUCKETS).padStart(5)}°  ${ax ? "col" : "row"}   ${row.join(" ")}`);
    }
    p("```");
    p();
  }

  // ── DP stats ──
  p("## DP oracle: cost, size, and how far to trust it");
  p();
  p("| face | vocab | K glyphs | labels/node (3K+1) | nodes n (median / max) | ms per stroke (median / p95) | cell conflicts | DP worse than current* |");
  p("|---|---|---|---|---|---|---|---|");
  for (const face of Object.keys(results.cases)) {
    for (const v of Object.keys(VOCABS)) {
      const recs = results.cases[face].filter((r) => r.dp[v]);
      if (!recs.length) continue;
      const own = Object.entries(STRATEGIES).filter(([, st]) => st.face === face && (st.vocab === "wire" ? "all" : st.vocab) === v);
      let worse = 0, tot = 0;
      for (const r of recs) for (const [n] of own) { const s = r.strategies[n]?.score; if (s) { tot++; if (r.dp[v].score.total > s.total + 1e-9) worse++; } }
      p(`| ${face} | ${v} | ${recs[0].dp[v].K} | ${recs[0].dp[v].labels} | ${median(recs.map((r) => r.dp[v].n))} / ${Math.max(...recs.map((r) => r.dp[v].n))} | ${f2(median(recs.map((r) => r.dp[v].ms)))} / ${f2(q(recs.map((r) => r.dp[v].ms), 0.95))} | ${recs.reduce((s, r) => s + r.dp[v].conflicts, 0)} | ${tot ? `${worse}/${tot}` : "–"} |`);
    }
  }
  p();
  p("\\* cases where the DP's full-rubric total is worse than the current strategy that shares its vocabulary — the surrogate/pruning gap made visible (the oracle is a heuristic optimum, an upper bound on the true best, not a proof).");
  p();
  p(`Pruning sensitivity (same DP, label sets widened from M = ${meta.M} to ${3 * meta.M}, on a fixed subset). The ink vocabulary has only 37 labels per node, so it is never pruned and serves as a control:`);
  p();
  p("| face | vocab | cases | mean total M | mean total 3M | cases improved by 3M |");
  p("|---|---|---|---|---|---|");
  for (const face of Object.keys(results.sensitivity)) {
    for (const v of ["all", "ink"]) {
      const pairs = results.sensitivity[face].map((s) => [byId[face].get(s.id)?.dp[v]?.score.total, s.dp[v]?.score.total]).filter(([a, b]) => a !== undefined && b !== undefined);
      if (!pairs.length) continue;
      p(`| ${face} | ${v} | ${pairs.length} | ${f3(mean(pairs.map((x) => x[0])))} | ${f3(mean(pairs.map((x) => x[1])))} | ${pairs.filter(([a, b]) => b < a - 1e-6).length} |`);
    }
  }
  p();
  fs.writeFileSync(file, L.join("\n") + "\n");
}
